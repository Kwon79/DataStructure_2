#define _CRT_SECURE_NO_WARNINGS

#include <stdio.h>
#include <string.h>

#include "TreeHw04.h"

int main(void)
{
    char input[1000];

    printf("========================================\n");
    printf("       이진트리 순회 프로그램\n");
    printf("========================================\n");

    printf("\n괄호 표기법으로 이진트리를 입력하세요.\n");
    printf("예: A(B(D,E),C(,F))\n\n");

    printf("입력: ");

    if (fgets(input, sizeof(input), stdin) == NULL)
    {
        printf("입력 오류입니다.\n");
        return 1;
    }

    /* 개행 제거 */
    input[strcspn(input, "\n")] = '\0';


    /* =====================================================
       트리 생성
       ===================================================== */

    BNode* root = build_tree(input);

    if (root == NULL)
    {
        return 1;
    }


    /* =====================================================
       트리 구조 출력
       ===================================================== */

    printf("\n========================================\n");
    printf("입력된 이진트리\n");
    printf("========================================\n");

    print_tree(root);


    /* =====================================================
       전위 순회
       ===================================================== */

    printf("\n========================================\n");
    printf("전위 순회 (Preorder)\n");
    printf("Root → Left → Right\n");
    printf("========================================\n");

    preorder(root);

    printf("\n");


    /* =====================================================
       중위 순회
       ===================================================== */

    printf("\n========================================\n");
    printf("중위 순회 (Inorder)\n");
    printf("Left → Root → Right\n");
    printf("========================================\n");

    inorder(root);

    printf("\n");


    /* =====================================================
       후위 순회
       ===================================================== */

    printf("\n========================================\n");
    printf("후위 순회 (Postorder)\n");
    printf("Left → Right → Root\n");
    printf("========================================\n");

    postorder(root);

    printf("\n");


    /* =====================================================
       메모리 해제
       ===================================================== */

    destroy_tree(root);

    return 0;
}